import { test, expect } from "@playwright/test"

test("home water keeps moving without a pointer and stops for reduced motion", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/")
  const water = page.locator(".home-wash")
  const canvas = water.locator("canvas")
  await expect(water).toHaveAttribute("data-playing", "true")
  await expect(canvas).toHaveAttribute("data-ready", "true")
  const frame = () => canvas.evaluate((node) => (node as HTMLCanvasElement).toDataURL())
  // Regression: the previous background stopped after its five-second intro.
  await page.waitForTimeout(5500)
  const afterIntro = await frame()
  await expect.poll(frame).not.toBe(afterIntro)

  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect(water).toHaveAttribute("data-playing", "false")
  const still = await frame()
  await page.waitForTimeout(350)
  expect(await frame()).toBe(still)

  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.locator("footer").scrollIntoViewIfNeeded()
  await expect(water).toHaveAttribute("data-playing", "false")
  const offscreen = await frame()
  await page.waitForTimeout(350)
  expect(await frame()).toBe(offscreen)
})

test("reduced motion preserves hydration and keyboard service exploration", async ({ page }) => {
  const errors: string[] = []
  page.on("pageerror", (error) => errors.push(error.message))
  page.on("console", (message) => {
    // The production analytics script is served by Vercel, not the local Next server.
    if (message.type() === "error" && !message.location().url.includes("/_vercel/insights/")) {
      errors.push(message.text())
    }
  })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/")
  const choices = page.getByRole("group", { name: "Neyi yıkatalım?" })
  await expect(choices.getByRole("button")).toHaveCount(5)
  for (const name of ["Ayakkabı", "Kuru temizleme", "Ütü", "Çamaşır", "Yorgan & battaniye"]) {
    const choice = choices.getByRole("button", { name, exact: true })
    await choice.focus()
    await choice.press("Enter")
    const sheet = page.getByRole("dialog", { name, exact: true })
    await expect(sheet).toBeVisible()
    await expect(sheet).toHaveAttribute("data-instant", "true")
    const url = new URL((await sheet.getByRole("link", { name: "WhatsApp’tan sor" }).getAttribute("href"))!)
    expect(url.pathname).toBe("/908503033193")
    expect(url.searchParams.get("text")).toBe(`Merhaba, ${name.toLocaleLowerCase("tr-TR")} için bilgi almak istiyorum.`)
    await expect(sheet.getByRole("link", { name: "Uygulamayı aç" })).toHaveAttribute("href", "https://app.yikat.tech")
    await page.keyboard.press("Escape")
    await expect(sheet).not.toBeVisible()
    await expect(choice).toBeFocused()
  }
  const shoes = choices.getByRole("button", { name: "Ayakkabı", exact: true })
  await shoes.click()
  const sheet = page.getByRole("dialog", { name: "Ayakkabı", exact: true })
  await sheet.getByRole("button", { name: "Uygulamayı indir" }).click()
  await expect(sheet).not.toBeVisible()
  const download = page.getByRole("dialog", { name: "Uygulamayı indir" })
  await expect(download).toBeVisible()
  await expect(download.getByRole("link", { name: "App Store’dan indir" })).toBeVisible()
  await page.keyboard.press("Escape")
  await expect(download).not.toBeVisible()
  await expect(shoes).toBeFocused()
  expect(errors).toEqual([])
})

